// Declarar as variáveis
let entradaA: string;
let entradaB: string;
let A: number;
let B: number;
let SOMA: number;

// Entrada de dados
entradaA = prompt('Digite A: ')!;
entradaB = prompt('Digite B: ')!;

// Processamento dos dados
A = parseInt(entradaA);
B = parseInt(entradaB);
SOMA = A + B;

// Saída de dados
console.log(`SOMA = ${SOMA}`);
